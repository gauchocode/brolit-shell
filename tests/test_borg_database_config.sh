#!/usr/bin/env bash
# Generation and convergence of the borgmatic database configs
# (libs/local/borg_database_config.sh).
set -uo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
TMP="$(mktemp -d)"
trap 'rm -rf "${TMP}"' EXIT
fail() { echo "FAIL: $*" >&2; exit 1; }

log_event() { echo "${1}: ${2}" >>"${TMP}/log"; }
# shellcheck disable=SC1091
source "${ROOT_DIR}/libs/local/borg_database_inventory.sh"
# shellcheck disable=SC1091
source "${ROOT_DIR}/libs/local/borg_database_config.sh"

export BROLIT_MAIN_DIR="/root/brolit-shell" PROJECTS_PATH="${TMP}/www" BROLIT_CONFIG_FILE="${TMP}/conf.json"
export BROLIT_BORGMATIC_DB_CONFIG_DIR="${TMP}/cfg" BROLIT_BORG_DB_STATE_FILE="${TMP}/state.tsv"
mkdir -p "${PROJECTS_PATH}/app.stellacast.com" "${TMP}/bin"
echo '{"BACKUPS":{"config":[{}]}}' >"${BROLIT_CONFIG_FILE}"
BACKUP_BORG_USERS=(u372319 u391408); BACKUP_BORG_SERVERS=(u372319.your-storagebox.de u391408.your-storagebox.de); BACKUP_BORG_PORTS=(23 23)
BACKUP_BORG_GROUP="stellacast-hosts"; HOSTNAME="stellacast-vm"

# ---- fake borgmatic: version from a file, `config validate` accepts unless the file says INVALID
cat >"${TMP}/bin/borgmatic" <<'EOF'
#!/usr/bin/env bash
if [[ "${1:-}" == "--version" ]]; then cat "${FAKE_BM_VERSION_FILE}"; exit 0; fi
if [[ "${1:-}" == "config" && "${2:-}" == "validate" ]]; then
  grep -q "INVALID" "${4}" && exit 1
  [[ "${FAKE_VALIDATE_RC:-0}" -eq 0 ]] || exit 1
  exit 0
fi
exit 0
EOF
chmod +x "${TMP}/bin/borgmatic"
_borgmatic_resolve_cmd() { echo "${TMP}/bin/borgmatic"; }
export FAKE_BM_VERSION_FILE="${TMP}/bm_version"; echo "2.1.10" >"${FAKE_BM_VERSION_FILE}"

# ---- 1. version comparison and the minimum -----------------------------------
for pair in "2.0.8 2.0.8 y" "2.0.6 2.0.8 n" "2.1.10 2.0.8 y" "1.9.4 2.0.8 n" "2.10.0 2.2.0 y" "2.0.8 2.1.7 n"; do
  read -r a b want <<<"${pair}"
  bdb_version_at_least "${a}" "${b}" && got=y || got=n
  [[ "${got}" == "${want}" ]] || fail "version ${a} >= ${b} should be ${want}"
done

# ---- 2. render: exact content for MariaDB and PostgreSQL containers and the host --
rows="${TMP}/rows.tsv"
printf 'compose\tapp.stellacast.com/mariadb\tmariadb\tstellacast-prod_mariadb\tapp_stellacast_prod\n' >"${rows}"
printf 'container\tpgx\tpostgres\tpgx\tappdb\n' >>"${rows}"
printf 'host\thost\tmysql\t-\tlegacy_db\n' >>"${rows}"
bdb_render_config "app.stellacast.com" "${rows}" >"${TMP}/out.yml" || fail "render failed"
cat >"${TMP}/expected.yml" <<'EOF'
# Generated by brolit-shell and regenerated every night: do not edit.
# Which databases are backed up, and under which owner, is decided by the
# ownership rules and by the decisions recorded in the Brolit configuration.
constants:
  project: "app.stellacast.com"
  group: "stellacast-hosts"
  hostname: "stellacast-vm"
  user_1: "u372319"
  server_1: "u372319.your-storagebox.de"
  port_1: "23"
  user_2: "u391408"
  server_2: "u391408.your-storagebox.de"
  port_2: "23"
repositories:
  - path: ssh://{user_1}@{server_1}:{port_1}/home/applications/{group}/{hostname}/projects-online/database/{project}
    label: storage-{user_1}
  - path: ssh://{user_2}@{server_2}:{port_2}/home/applications/{group}/{hostname}/projects-online/database/{project}
    label: storage-{user_2}
archive_name_format: '{project}_database-{now:%Y-%m-%dT%H:%M:%S}'
keep_daily: 7
keep_weekly: 4
keep_monthly: 6
keep_yearly: 1
checks:
  - name: archives
check_last: 3
mariadb_databases:
  - name: "app_stellacast_prod"
    hostname: "stellacast-prod_mariadb"
    mariadb_dump_command: "/root/brolit-shell/utils/borg/db_exec.sh dump mariadb stellacast-prod_mariadb"
    mariadb_command: "/root/brolit-shell/utils/borg/db_exec.sh client mariadb stellacast-prod_mariadb"
    password_transport: environment
    options: --single-transaction --quick
mysql_databases:
  - name: "legacy_db"
    options: --single-transaction --quick
postgresql_databases:
  - name: "appdb"
    hostname: "pgx"
    format: custom
    pg_dump_command: "/root/brolit-shell/utils/borg/db_exec.sh dump postgres pgx"
    pg_restore_command: "/root/brolit-shell/utils/borg/db_exec.sh restore postgres pgx"
    psql_command: "/root/brolit-shell/utils/borg/db_exec.sh client postgres pgx"
commands:
  - after: error
    run:
      - echo "Borgmatic database backup failed for {project}; see the brolit backup log for the classified reason"
EOF
diff -u "${TMP}/expected.yml" "${TMP}/out.yml" >"${TMP}/diff.txt" || { cat "${TMP}/diff.txt" >&2; fail "rendered config differs from the expected one"; }
grep -qiE "password:|passwd|MYSQL_PWD|secret" "${TMP}/out.yml" && fail "a rendered config must not carry a credential"

# ---- 3. render refuses values that are not safe to write ---------------------
printf 'compose\ts\tmariadb\tc\tbad"name\n' >"${TMP}/bad1.tsv"
bdb_render_config p "${TMP}/bad1.tsv" >/dev/null 2>&1 && fail "a database name with a quote must be refused"
printf 'compose\ts\tmariadb\tc;rm -rf /\tdb\n' >"${TMP}/bad2.tsv"
bdb_render_config p "${TMP}/bad2.tsv" >/dev/null 2>&1 && fail "a container name with shell characters must be refused"
bdb_render_config 'p"x' "${rows}" >/dev/null 2>&1 && fail "an owner with a quote must be refused"
SAVE=("${BACKUP_BORG_USERS[@]}"); BACKUP_BORG_USERS=()
bdb_render_config p "${rows}" >/dev/null 2>&1 && fail "no storage destinations must be refused"
BACKUP_BORG_USERS=("${SAVE[@]}")
: >"${TMP}/empty.tsv"; bdb_render_config p "${TMP}/empty.tsv" >/dev/null 2>&1 && fail "a config with no database must not be rendered"

# ---- 4. converge ------------------------------------------------------------
# Inventory of the real stellacast-vm situation, reduced: the live container database,
# a small unmatched host database, and a dormant giant duplicate of the live name.
bdb_collect() {
  printf 'compose\tapp.stellacast.com/mariadb\tmariadb\tstellacast-prod_mariadb\tapp_stellacast_prod\tapp.stellacast.com\tstructure\t15000\t107527\tno\n'
  printf 'host\thost\tmysql\t-\tstellacast_tmp\t-\tnone\t22\t0\tyes\n'
  printf 'host\thost\tmysql\t-\tapp_stellacast_prod\t-\tnone\t14883\t0\tyes\n'
}
bdb_converge; rc=$?
[[ ${rc} -eq 0 ]] || fail "converge rc=${rc}: $(cat "${TMP}/log")"
D="${TMP}/cfg"
[[ -f "${D}/app.stellacast.com.yml" ]] || fail "the project config must exist"
[[ -f "${D}/standalone-host-stellacast_tmp.yml" ]] || fail "the small unmatched database must be dumped as standalone"
[[ "$(ls "${D}"/*.yml | wc -l)" -eq 2 ]] || fail "the held database must not get a config: $(ls "${D}")"
[[ "$(stat -c %a "${D}/app.stellacast.com.yml")" == "600" ]] || fail "config mode must be 600"
grep -q 'name: "app_stellacast_prod"' "${D}/app.stellacast.com.yml" || fail "the live database is in its project config"
grep -q 'stellacast_tmp' "${D}/app.stellacast.com.yml" && fail "a standalone database must not leak into the project config"
awk -F'\t' '$5=="app_stellacast_prod" && $2=="host" {print $11"|"$13"|"$14}' "${BROLIT_BORG_DB_STATE_FILE}" | grep -qx "held|held-dormant|1" || fail "the state file must carry the resolved inventory"

# ---- 5. idempotent: nothing changes, nothing is retired ----------------------
before="$(cat "${D}"/*.yml | sha256sum)"; ino="$(stat -c %i "${D}/app.stellacast.com.yml")"
bdb_converge || fail "second converge"
[[ "$(cat "${D}"/*.yml | sha256sum)" == "${before}" && "$(stat -c %i "${D}/app.stellacast.com.yml")" == "${ino}" ]] || fail "an unchanged inventory must not rewrite the config"
[[ -z "$(ls -A "${D}/.retired")" ]] || fail "nothing to retire yet: $(ls -A "${D}/.retired")"

# ---- 6. a decision removes what it ignores: the config is retired, not deleted ----
echo '{"BACKUPS":{"config":[{"databases":{"decisions":[{"source":"host","database":"stellacast_tmp","decision":"ignore"}]}}]}}' >"${BROLIT_CONFIG_FILE}"
bdb_converge || fail "converge after the decision"
[[ ! -e "${D}/standalone-host-stellacast_tmp.yml" ]] || fail "an ignored database must lose its config"
ls "${D}/.retired" | grep -q "^standalone-host-stellacast_tmp\." || fail "the retired config must be kept"

# ---- 7. a config borgmatic refuses is never installed and the previous one stays --
echo '{"BACKUPS":{"config":[{"databases":{"decisions":[{"source":"host","database":"app_stellacast_prod","decision":"standalone"}]}}]}}' >"${BROLIT_CONFIG_FILE}"
export FAKE_VALIDATE_RC=1
bdb_converge; rc=$?
[[ ${rc} -eq 1 ]] || fail "a rejected config must make converge fail, rc=${rc}"
[[ ! -e "${D}/standalone-host-app_stellacast_prod.yml" ]] || fail "a rejected config must not be installed"
[[ -f "${D}/app.stellacast.com.yml" ]] || fail "the previous config must stay when validation fails"
unset FAKE_VALIDATE_RC
bdb_converge || fail "converge once borgmatic accepts it"
[[ -f "${D}/standalone-host-app_stellacast_prod.yml" ]] || fail "standalone decision must be honoured (large and dormant, but explicit)"

# ---- 8. borgmatic below the minimum: raised by the shell, or nothing is done ----
rm -rf "${D}"; echo '{"BACKUPS":{"config":[{}]}}' >"${BROLIT_CONFIG_FILE}"
echo "2.0.6" >"${FAKE_BM_VERSION_FILE}"
PATH_SAVE="${PATH}"; export PATH="${TMP}/nopipx:/usr/bin:/bin"; mkdir -p "${TMP}/nopipx"
bdb_converge; rc=$?
[[ ${rc} -eq 2 ]] || fail "too old and no pipx must return 2, got ${rc}"
[[ ! -d "${D}" || -z "$(ls -A "${D}"/*.yml 2>/dev/null)" ]] || fail "nothing may be configured under a too-old borgmatic"
export PATH="${TMP}/pipxbin:${PATH_SAVE}"; mkdir -p "${TMP}/pipxbin"
cat >"${TMP}/pipxbin/pipx" <<'EOF'
#!/usr/bin/env bash
echo "pipx $*" >>"${PIPX_LOG}"
[[ "${1:-}" == "upgrade" ]] && echo "2.1.10" >"${FAKE_BM_VERSION_FILE}"
exit 0
EOF
chmod +x "${TMP}/pipxbin/pipx"; export PIPX_LOG="${TMP}/pipx.log"; : >"${PIPX_LOG}"
bdb_converge; rc=$?
[[ ${rc} -eq 0 ]] || fail "pipx must raise borgmatic and converge, rc=${rc}"
grep -q "pipx upgrade borgmatic" "${PIPX_LOG}" || fail "pipx upgrade not called"
[[ -f "${D}/app.stellacast.com.yml" ]] || fail "after raising borgmatic the configs must be written"
: >"${PIPX_LOG}"; bdb_converge >/dev/null; [[ ! -s "${PIPX_LOG}" ]] || fail "an adequate borgmatic must not be touched"

echo "borg database config tests passed"
